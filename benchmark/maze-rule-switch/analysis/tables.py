"""Reference-format tables for the 12x12 100-session run. No model calls.

  python -m analysis.tables      # writes results/METRICS_TABLE.md and results/per_problem/def{2,1}.{md,csv}

MPE here is the reference metric: share of graded submissions that violate the round's own constraint (not the persistent
error rate of analysis/verdict.py). Definition 1 counts every graded submission of rounds 2-8; definition 2 counts those
after the first submission judged incorrect in the round. Mean error = share of incorrect graded submissions (rounds 1-8).
Session values are averaged over rounds, then over sessions. API time = sum of per-call wall times (calls run in parallel,
so it is not elapsed time). Cost = tokens x price per million (data/api_prices.json).
"""
import csv

import numpy as np

from maze.loop import path_cells, from_dict

from .common import COLOURS, MODELS, ROOT, SPEC, cost, load

RULES = [("NB", "No-backtrack restrictions"), ("AV", "Non-goal-cell restrictions"), ("VIA", "Via-point restrictions")]
NAMES = {"gpt-6.1-sol": "GPT-6.1 Sol", "claude-opus-5-5": "Claude Opus 5.5", "claude-sonnet-5": "Claude Sonnet 5"}
SIDS = sorted(SPEC)
R = list(range(2, 9))
MAZES = {}


def violates(r):
    """True / False for a submission with a walk; None when there is no walk to check."""
    if r["moves"] is None:
        return None
    m = MAZES.setdefault(r["session"], from_dict(SPEC[r["session"]]["maze"]))
    cells, _ = path_cells(m, m.points[r["start"]], r["moves"])
    if cells is None:
        return None
    oth = {m.points[c] for c in ("green", "red", "blue", "yellow") if c not in (r["start"], r["goal"])}
    if r["rule"] == "NB":
        return len(set(cells)) != len(cells)
    if r["rule"] == "AV":
        return bool(oth & set(cells))
    return not (oth & set(cells[:-1]))


def block(rows, rule=None):
    sel = [r for r in rows if rule is None or r["rule"] == rule]
    graded = [r for r in sel if r.get("counted", True) and r["fail"] != "refusal"]
    by = {}
    for r in graded:
        by.setdefault((r["session"], r["round"]), []).append(r)
    per, per2, err = {}, {}, {}
    for (s, k), v in by.items():
        err.setdefault(s, []).append(100 * sum(not r["ok"] for r in v) / len(v))
        if k >= 2:
            per.setdefault(s, []).append(100 * sum(bool(violates(r)) for r in v) / len(v))
            vs = sorted(v, key=lambda r: r["attempt_in_round"])
            j = next((i for i, r in enumerate(vs) if not r["ok"]), None)
            after = vs[j + 1:] if j is not None else []
            if after:
                per2.setdefault(s, []).append(100 * sum(bool(violates(r)) for r in after) / len(after))
    mean = lambda d: (sum(sum(v) / len(v) for v in d.values()) / len(d)) if d else None  # noqa: E731
    secs = [r["api"].get("api_seconds") for r in sel]
    return {"n_mpe": len(per), "n_all": len(err), "mpe": mean(per), "mpe2": mean(per2), "me": mean(err),
            "api_min": sum(secs) / 60 if secs and all(x is not None for x in secs) else None, "cost": cost(sel)}


def metrics_table():
    f2 = lambda x: "" if x is None else f"{x:.2f}"  # noqa: E731
    L = ["# Reference-format metrics table: 12×12 maze, 100 sessions, reasoning effort medium", "",
         "MPE = share of submissions violating the round's own constraint (definition 1: all submissions of rounds 2–8; definition 2: from the submission",
         "after the first incorrect one). Mean error = rounds 1–8. API time = sum of per-call times (sessions ran in parallel; not elapsed time). Generated by",
         "`python -m analysis.tables`.", ""]
    for cond, title in (("feedback", "Feedback condition (100 sessions)"), ("nofeedback", "Baseline, no feedback (10 sessions)")):
        L += [f"## {title}", "", "| Restriction type | N | MPE (%) 정의 1 | MPE (%) 정의 2 | Mean error (%) | API time (min) | Cost (USD) |", "|---|---|---|---|---|---|---|"]
        for m in MODELS:
            rows = load(cond, m, graded=False)
            L.append(f"| **{NAMES[m]}** | | | | | | |")
            for key, lab in RULES + [(None, "Total")]:
                b = block(rows, key)
                cells = [f"{b['n_mpe']}/{b['n_all']}", f2(b["mpe"]), f2(b["mpe2"]), f2(b["me"]), f2(b["api_min"]), f"{b['cost']:.4f}"]
                L.append(f"| {lab} | " + " | ".join(cells) + " |" if key else "| **Total** | " + " | ".join(f"**{c}**" for c in cells) + " |")
        L.append("")
    L += ["Known limitation: when a run stopped in the middle of a step (claude-opus-5-5 feedback step 14, claude-sonnet-5 feedback steps 21 and 76), calls",
          "already answered in that step were not recorded, so API time and Cost here are slightly too low (at most about $15 for claude-sonnet-5). Verdicts are",
          "not affected: those attempts were asked again after resuming. The session runner now records each chunk of sessions as soon as it is answered.", ""]
    (ROOT / "results/METRICS_TABLE.md").write_text("\n".join(L) + "\n")


def per_problem_values(m, definition):
    graded = load("feedback", m)
    by = {}
    for r in graded:
        by.setdefault((r["session"], r["round"]), []).append(r)
    out = {}
    for s in SIDS:
        per, err, rules, unreached, played = {}, {}, {}, set(), set()
        for k in range(1, 9):
            v = sorted(by.get((s, k), []), key=lambda r: r["attempt_in_round"])
            rules[k] = SPEC[s]["rounds"][k - 1]["rule"]
            if not v:
                continue
            played.add(k)
            if v[-1].get("round_end") and not v[-1].get("round_reached"):
                unreached.add(k)
            err[k] = 100 * sum(not r["ok"] for r in v) / len(v)
            if k < 2:
                continue
            if definition == 2:
                j = next((i for i, r in enumerate(v) if not r["ok"]), None)
                v = v[j + 1:] if j is not None else []
            per[k] = 100 * sum(bool(violates(r)) for r in v) / len(v) if v else None
        out[s] = {"per": per, "err": err, "rules": rules, "unreached": unreached, "played": played}
    return out


def row_vals(x, rule):
    cells, per, unr = [], [], []
    for k in R:
        if k not in x["played"] or x["rules"][k] != rule:
            cells.append("–"); per.append(None); unr.append(0)
            continue
        v = x["per"].get(k)
        txt = "·" if v is None else f"{v:.1f}"
        if k in x["unreached"]:
            txt += "†"
        cells.append(txt); per.append(v); unr.append(int(k in x["unreached"]))
    pv = [v for v in per if v is not None]
    ev = [x["err"][k] for k in x["err"] if x["rules"][k] == rule]
    return cells, per, unr, (float(np.mean(pv)) if pv else None), (float(np.mean(ev)) if ev else None)


def fm(v, d=1):
    return "–" if v is None else f"{v:.{d}f}"


def html_table(T, rule, label, sids, summary=False):
    h = ["<table>", "<thead>",
         "<tr><th rowspan=\"3\">Problem</th>" + "".join(f"<th colspan=\"{len(R) + 2}\"><b>{NAMES[m]}</b></th>" for m in MODELS) + "</tr>",
         "<tr>" + "".join(f"<th colspan=\"{len(R) + 2}\"><i>{label}</i></th>" for _ in MODELS) + "</tr>",
         "<tr>" + "".join("".join(f"<th>R{k}</th>" for k in R) + "<th>MPE</th><th>Error</th>" for _ in MODELS) + "</tr>",
         "</thead>", "<tbody>"]
    cols = {m: [row_vals(T[m][s], rule) for s in SIDS] for m in MODELS}
    if not summary:
        for i, s in enumerate(SIDS):
            if s in sids:
                h.append(f"<tr><td>{s}</td>" + "".join("".join(f"<td>{c}</td>" for c in cols[m][i][0]) +
                                                         f"<td>{fm(cols[m][i][3])}</td><td>{fm(cols[m][i][4])}</td>" for m in MODELS) + "</tr>")
    else:
        mean_tds, n_tds = "", ""
        for m in MODELS:
            for j in range(len(R)):
                v = [c[1][j] for c in cols[m] if c[1][j] is not None]
                mean_tds += f"<td><b>{fm(float(np.mean(v)) if v else None)}</b></td>"
                n_tds += f"<td>{len(v)}</td>"
            mp = [c[3] for c in cols[m] if c[3] is not None]
            er = [c[4] for c in cols[m] if c[4] is not None]
            mean_tds += f"<td><b>{fm(float(np.mean(mp)) if mp else None, 2)}</b></td><td><b>{fm(float(np.mean(er)) if er else None, 2)}</b></td>"
            n_tds += f"<td>{len(mp)}</td><td>{len(er)}</td>"
        h += [f"<tr><td><b>Mean</b></td>{mean_tds}</tr>", f"<tr><td><b>N</b></td>{n_tds}</tr>"]
    return h + ["</tbody>", "</table>"], cols


def per_problem(definition):
    T = {m: per_problem_values(m, definition) for m in MODELS}
    md = [f"# Per-problem tables, reference layout (definition {definition})", "",
          "One set per restriction type, three models side by side. A cell is the session's round MPE (%) when the round used that restriction; – another",
          "restriction or not played; · (definition 2) a round of that restriction with no submission after its first incorrect one; † unreached round (no",
          "three correct in a row within 15 attempts). MPE = mean over the session's R2–R8 rounds of that restriction; Error = mean error rate over its R1–R8",
          "rounds of that restriction. Sessions are grouped by start colour (25 each), with a 100-session summary per restriction.", ""]
    rows = [["rule_set", "problem", "start"] + [f"{m}:{c}" for m in MODELS for c in [f"R{k}" for k in R] + ["MPE", "Error"] + [f"R{k}_unreached" for k in R]]]
    for rule, label in [(r, l.replace(" restrictions", "")) for r, l in RULES]:
        md += [f"## {label} restrictions ({rule})", ""]
        for col in COLOURS:
            sids = [s for s in SIDS if SPEC[s]["start"] == col]
            md += [f"### {label} · start {col} ({len(sids)} sessions)", ""] + html_table(T, rule, label, sids)[0] + [""]
        md += [f"### {label} · all 100 sessions", ""]
        h, cols = html_table(T, rule, label, SIDS, summary=True)
        md += h + [""]
        for i, s in enumerate(SIDS):
            r = [label, s, SPEC[s]["start"]]
            for m in MODELS:
                _, per, unr, mp, er = cols[m][i]
                r += ["" if v is None else f"{v:.4f}" for v in per] + ["" if mp is None else f"{mp:.4f}", "" if er is None else f"{er:.4f}"] + unr
            rows.append(r)
        for lab in ("Mean", "N"):
            r = [label, lab, ""]
            for m in MODELS:
                for j in range(len(R)):
                    v = [c[1][j] for c in cols[m] if c[1][j] is not None]
                    r.append((f"{np.mean(v):.4f}" if v else "") if lab == "Mean" else str(len(v)))
                mp = [c[3] for c in cols[m] if c[3] is not None]
                er = [c[4] for c in cols[m] if c[4] is not None]
                r += ([f"{np.mean(mp):.4f}" if mp else "", f"{np.mean(er):.4f}" if er else ""] if lab == "Mean" else [str(len(mp)), str(len(er))])
                r += [""] * len(R)
            rows.append(r)
    d = ROOT / "results/per_problem"
    d.mkdir(parents=True, exist_ok=True)
    (d / f"def{definition}.md").write_text("\n".join(md) + "\n")
    with (d / f"def{definition}.csv").open("w", newline="") as fh:
        csv.writer(fh).writerows(rows)


def main():
    metrics_table()
    for dfn in (2, 1):
        per_problem(dfn)
    print("wrote results/METRICS_TABLE.md and results/per_problem/def{2,1}.{md,csv}")


if __name__ == "__main__":
    main()
